#!/usr/bin/env node
/**
 * Build the lucide icon sprite.
 *
 * Reads the icon node data straight out of lucide-react, so the path data is
 * verbatim. Hand-approximated SVG paths render as broken glyphs.
 *
 * The sprite carries no style attribute: the production CSP is
 * `style-src 'self'`, which also blocks style="" in injected markup. It is
 * hidden by the .icon-sprite class (src/styles/base.css).
 *
 * Emits: src/icons/sprite.generated.ts (the sprite markup plus an IconName union)
 * Usage: node scripts/build_icons.mjs
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const OUT = resolve(ROOT, 'src/icons/sprite.generated.ts');

// Every icon the application uses, by lucide name. Add here, never inline.
const ICONS = [
  'arrow-left',
  'book-open-text',
  'bookmark',
  'bookmark-check',
  'check',
  'chevron-down',
  'chevron-right',
  'clock',
  'download',
  'external-link',
  'heart',
  'info',
  'layers',
  'library',
  'map-pin',
  'menu',
  'monitor',
  'moon',
  'rotate-ccw',
  'search',
  'sliders-horizontal',
  'sun',
  'triangle-alert',
  'upload',
  'users',
  'x',
];

const attrs = (o) =>
  Object.entries(o)
    .filter(([k]) => k !== 'key')
    .map(([k, v]) => `${k}="${String(v)}"`)
    .join(' ');

const symbols = [];
for (const name of ICONS) {
  const mod = await import(`lucide-react/dist/esm/icons/${name}.mjs`);
  // lucide-react 1.x exports `__iconData.node`; 0.x exported `__iconNode`.
  const nodes = mod.__iconData?.node ?? mod.__iconNode;
  if (!Array.isArray(nodes)) throw new Error(`No icon node data for "${name}".`);
  const children = nodes.map(([tag, a]) => `<${tag} ${attrs(a)}/>`).join('');
  symbols.push(`<symbol id="i-${name}" viewBox="0 0 24 24">${children}</symbol>`);
}

const sprite =
  '<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false" class="icon-sprite">' +
  symbols.join('') +
  '</svg>';

const ts = `// Generated by scripts/build_icons.mjs from lucide-react. Do not edit by hand.
// Icon path data is verbatim lucide, under the ISC license.

export type IconName =
${ICONS.map((n) => `  | '${n}'`).join('\n')};

export const ICON_NAMES: readonly IconName[] = [
${ICONS.map((n) => `  '${n}',`).join('\n')}
] as const;

export const ICON_SPRITE = ${JSON.stringify(sprite)};
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, ts);
console.log(`build_icons: ${ICONS.length} icons -> src/icons/sprite.generated.ts`);
