#!/usr/bin/env node
/**
 * Generate deploy/Caddyfile from project.config.json, the single rename point.
 *
 *   node scripts/deploy-config.mjs           write deploy/Caddyfile
 *   node scripts/deploy-config.mjs --check   exit 1 if the committed file is stale (CI)
 *
 * While `private` is true the site sits behind basic auth and asks search engines
 * not to index it. The credentials are environment variables on the server, never
 * in the repo: <SLUG>_AUTH_USER and <SLUG>_AUTH_HASH (a `caddy hash-password` hash).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const OUT = resolve(ROOT, 'deploy/Caddyfile');
const cfg = JSON.parse(readFileSync(resolve(ROOT, 'project.config.json'), 'utf8'));
const env = cfg.slug.toUpperCase().replace(/[^A-Z0-9]/g, '_');

const auth = cfg.private
  ? `
	# Private until the public launch: set "private": false in project.config.json,
	# regenerate, and reload Caddy. Credentials live in the server's environment;
	# without them every request gets 401. \`basicauth\`, not \`basic_auth\`: the
	# new spelling needs Caddy 2.8, and 2.8 and later still accept this one.
	basicauth {
		{$${env}_AUTH_USER} {$${env}_AUTH_HASH}
	}
`
  : '';

const robots = cfg.private ? '\n\t\tX-Robots-Tag "noindex, nofollow"' : '';

const caddyfile = `# Generated by scripts/deploy-config.mjs from project.config.json. Do not edit by hand.
#
# ${cfg.name} on a server running Caddy. Layout:
#
#   ${cfg.deployPath}/dist     the web app, \`npm run build\` output (deployed by CI)
#   ${cfg.deployPath}/deploy   this file
#
# Import it from the main Caddyfile:   import ${cfg.deployPath}/deploy/Caddyfile
# TLS is automatic once ${cfg.host} resolves to this host. docs/DEPLOYMENT.md.

${cfg.host} {
	# The build ships .br, .zst and .gz sidecars (scripts/compress-dist.mjs), served
	# by file_server below. encode only covers responses without a sidecar.
	encode zstd gzip
${auth}
	root * ${cfg.deployPath}/dist

	# Content-hashed names never change: Vite's assets/ and the hashed catalogue.
	@immutable path_regexp ^/(assets/|data/catalog\\.[0-9a-f]+\\.json$)
	header @immutable Cache-Control "public, max-age=31536000, immutable"

	# Everything else revalidates: the HTML (also when an app route such as
	# /stories/x is rewritten to it below), the service worker, the manifest and
	# the plain catalogue. Cached, a release would never reach anyone who has
	# opened the site once. "?" only sets it where no rule above did.
	header ?Cache-Control "no-cache"

	# Icons keep their names across releases: a week is a safe middle ground.
	@icons path /favicon.svg /favicon.ico /apple-touch-icon.png /icon-192.png /icon-512.png /maskable-512.png
	header @icons Cache-Control "public, max-age=604800"

	# History routing: any path that is not a file is an app route (docs/adr/0002).
	try_files {path} /index.html
	file_server {
		precompressed br zstd gzip
	}

	header {
		Strict-Transport-Security "max-age=31536000; includeSubDomains"
		X-Content-Type-Options "nosniff"
		Referrer-Policy "strict-origin-when-cross-origin"
		Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=()"
		# Everything is self-hosted. No inline scripts or styles anywhere (eslint enforces it).
		Content-Security-Policy "default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:; font-src 'self'; connect-src 'self'; worker-src 'self'; manifest-src 'self'; object-src 'none'; base-uri 'none'; form-action 'self'; frame-ancestors 'none'"${robots}
		-Server
	}

	log {
		output file /var/log/caddy/${cfg.slug}.access.log {
			roll_size 50MiB
			roll_keep 5
		}
		format console
	}
}
`;

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== caddyfile) {
    console.error(
      'deploy/Caddyfile is out of date with project.config.json: run `npm run deploy:config`',
    );
    process.exit(1);
  }
  console.log('deploy/Caddyfile matches project.config.json');
} else {
  writeFileSync(OUT, caddyfile);
  console.log(`wrote deploy/Caddyfile for ${cfg.host}`);
}
