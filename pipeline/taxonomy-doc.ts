/** Generate docs/taxonomy-reference.md from tagging/taxonomy/*.yaml. Never edit the output by hand. */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { TermDef } from '../shared/taxonomy.ts';
import { ROOT } from './lib/paths.ts';
import { loadTaxonomy } from './lib/taxonomy.ts';

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

function termTable(terms: TermDef[], grouped: boolean): string[] {
  const rows: string[] = [];
  let group: string | undefined;
  for (const t of terms) {
    if (grouped && t.group !== group) {
      group = t.group;
      rows.push(
        '',
        `#### ${group ?? ''}`,
        '',
        '| id | label | definition | examples |',
        '|---|---|---|---|',
      );
    }
    rows.push(
      `| \`${t.id}\` | ${cell(t.label)} | ${cell(t.definition)} | ${cell((t.examples ?? []).join('; '))} |`,
    );
  }
  return grouped ? rows : ['| id | label | definition | examples |', '|---|---|---|---|', ...rows];
}

function main(): void {
  const t = loadTaxonomy();
  const year = (y: number | null) => (y === null ? 'present' : y < 0 ? `${-y} BCE` : String(y));
  const out = [
    '# Taxonomy reference',
    '',
    `Generated by \`npm run taxonomy:doc\` from \`tagging/taxonomy/\` (version ${t.version}). Do not edit by hand.`,
    'The reasoning behind these lists is in [TAXONOMY.md](TAXONOMY.md).',
    '',
    `## Formats (${t.formats.length})`,
    '',
    ...termTable(t.formats, false),
    '',
    `## Subject kinds (${t.subjectKinds.length})`,
    '',
    ...termTable(t.subjectKinds, false),
    '',
    `### Organization types (${t.orgTypes.length})`,
    '',
    ...termTable(t.orgTypes, false),
    '',
    `## Roles (${t.roles.length})`,
    ...termTable(t.roles, true),
    '',
    `## Themes (${t.themes.length})`,
    ...termTable(t.themes, true),
    '',
    `## Content warnings (${t.contentWarnings.length})`,
    '',
    ...termTable(t.contentWarnings, false),
    '',
    `## Polities (${t.polities.length})`,
    '',
    '| id | label | years | modern countries |',
    '|---|---|---|---|',
    ...t.polities.map(
      (p) =>
        `| \`${p.id}\` | ${p.label} | ${year(p.start)} to ${year(p.end)} | ${p.modern.join(', ')} |`,
    ),
    '',
    `## Eras (${t.eras.length})`,
    '',
    'Derived from `time.main_span` by overlap; never chosen by the agent. Centuries are computed and not listed.',
    '',
    '| id | label | years | scope | region hint |',
    '|---|---|---|---|---|',
    ...t.eras.map(
      (e) =>
        `| \`${e.id}\` | ${e.label} | ${year(e.start)} to ${year(e.end)} | ${e.scope} | ${e.region_hint ?? ''} |`,
    ),
    '',
  ];
  const path = join(ROOT, 'docs', 'taxonomy-reference.md');
  writeFileSync(path, out.join('\n'));
  console.log(`taxonomy:doc -> ${path}`);
}

if (import.meta.main) main();
