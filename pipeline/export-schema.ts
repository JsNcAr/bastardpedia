/** Write tagging/schema/story-tags.schema.json from the Zod schema and the current taxonomy. */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { z } from 'zod';
import { makeStoryTagsSchema } from '../shared/schemas/story-tags.ts';
import { vocabularies } from '../shared/taxonomy.ts';
import { ROOT } from './lib/paths.ts';
import { loadTaxonomy } from './lib/taxonomy.ts';

export const SCHEMA_FILE = join(ROOT, 'tagging', 'schema', 'story-tags.schema.json');

export function buildJsonSchema(): Record<string, unknown> {
  const taxonomy = loadTaxonomy();
  const { host } = JSON.parse(readFileSync(join(ROOT, 'project.config.json'), 'utf8')) as {
    host: string;
  };
  const schema = z.toJSONSchema(makeStoryTagsSchema(vocabularies(taxonomy)), {
    target: 'draft-2020-12',
    unrepresentable: 'any',
  });
  return {
    ...schema,
    $id: `https://${host}/schema/story-tags.schema.json`,
    title: `StoryTags (taxonomy ${taxonomy.version})`,
    description:
      'Generated by `npm run tags:schema` from shared/schemas/story-tags.ts and tagging/taxonomy/. Do not edit. ' +
      'Cross-field rules (a primary person needs a role, a setting is required unless scope is online, ' +
      'start <= end, no duplicate ids, org_type only on organizations) cannot be expressed here: ' +
      'run `npm run tags:validate` for the full check.',
  };
}

function main(): void {
  mkdirSync(dirname(SCHEMA_FILE), { recursive: true });
  writeFileSync(SCHEMA_FILE, `${JSON.stringify(buildJsonSchema(), null, 2)}\n`);
  console.log(`tags:schema -> ${SCHEMA_FILE}`);
}

if (import.meta.main) main();
