"""Rebuild every master SVG in brand/masters/ from the geometry and the wordmark font.

    python3 brand/tools/build_masters.py [--palette o2|a4] [--out brand/masters]

Colours come from PALETTES below, which mirror design-tokens.json (brand.mark,
brand.halo, text.primary and their dark values). Requires fonttools and brotli.
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from geometry import B, BOOK, HALO, TAIL  # noqa: E402
from pathops import transform as T  # noqa: E402
from wordmark import wordmark  # noqa: E402

PALETTES = {
    # O2, the chosen palette: site oxblood (oxblood.600) with warm gilt (gilt.500)
    'o2': {'mark': '#852D23', 'halo': '#B07A1E', 'ink': '#1F1C18',
           'mark_dark': '#D3877A', 'halo_dark': '#D9AE52', 'ink_dark': '#EFE9DE',
           'paper': '#F7F3EC'},
    # A4, kept as a proposal: episcopal violet with brass
    'a4': {'mark': '#56306A', 'halo': '#94762E', 'ink': '#1F1C18',
           'mark_dark': '#C9A9DB', 'halo_dark': '#D3B25E', 'ink_dark': '#EFE9DE',
           'paper': '#F7F3EC'},
}


def svg(title, body, vb):
    w, h = vb.split()[2:]
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}" width="{w}" height="{h}" '
            f'role="img" aria-labelledby="title">\n  <title id="title">{title}</title>\n{body}\n</svg>\n')


def symbol(k, dx, dy, mark, halo):
    # the symbol sits 4 units left of the geometry's origin for optical balance
    ox, oy = dx - 4 * k, dy + 4 * k
    return (f'    <path id="book" fill="{mark}" fill-rule="evenodd" d="{T(BOOK + " " + B, k, ox, oy)}"/>\n'
            f'    <path id="halo" fill="{halo}" fill-rule="evenodd" d="{T(HALO, k, ox, oy)}"/>\n'
            f'    <path id="tail" fill="{mark}" d="{T(TAIL, k, ox, oy)}"/>')


def build(p, out, suffix=''):
    out.mkdir(parents=True, exist_ok=True)
    d, width, _upm, cap, _xh = wordmark('Bastardpedia', 600, 32)

    def word(s, x, base, fill):
        return f'    <path id="wordmark" fill="{fill}" d="{T(d, s, x, base)}"/>'

    def write(name, title, body, vb):
        (out / f'{name}{suffix}.svg').write_text(svg(title, body, vb))

    # light (on paper), dark (on the dark page) and on-mark (on a tile in the mark colour)
    modes = {
        '': (p['mark'], p['halo'], p['ink']),
        '-dark': (p['mark_dark'], p['halo_dark'], p['ink_dark']),
        '-on-mark': (p['paper'], p['halo_dark'], p['paper']),
    }
    for tag, (mark, halo, ink) in modes.items():
        write(f'symbol{tag}', 'Bastardpedia symbol', f'  <g id="symbol">\n{symbol(1, 0, 0, mark, halo)}\n  </g>', '0 0 256 256')
        # small-size cut (16 to 24 px): no spine groove, halo or tail; book and B fill the frame
        k = 1.25
        small = T(BOOK.split(' M78')[0] + ' ' + B, k, 128 - 132 * k, 128 - 101 * k - 1)
        write(f'symbol-small{tag}', 'Bastardpedia symbol, small sizes',
              f'  <g id="symbol">\n    <path id="book" fill="{mark}" fill-rule="evenodd" d="{small}"/>\n  </g>', '0 0 256 256')
        # horizontal: cap height 84, cap centred on the book body (y 40..196)
        s = 84 / cap
        x0 = 194
        w = round(x0 + width * s + 20)
        write(f'lockup-horizontal{tag}', 'Bastardpedia logo, horizontal',
              f'  <g id="symbol">\n{symbol(1, -36, 0, mark, halo)}\n  </g>\n  <g id="name">\n{word(s, x0, 160, ink)}\n  </g>',
              f'0 0 {w} 256')
        # stacked: symbol 200 tall, wordmark cap height 70 below
        s2, k2 = 70 / cap, 200 / 256
        wst = round(width * s2 + 48)
        write(f'lockup-stacked{tag}', 'Bastardpedia logo, stacked',
              f'  <g id="symbol">\n{symbol(k2, (wst - 256 * k2) / 2, 0, mark, halo)}\n  </g>\n'
              f'  <g id="name">\n{word(s2, 24, 298, ink)}\n  </g>', f'0 0 {wst} 326')
        s3 = 120 / cap
        write(f'wordmark{tag}', 'Bastardpedia wordmark',
              f'  <g id="name">\n{word(s3, 16, 136, ink)}\n  </g>', f'0 0 {round(width * s3 + 32)} 180')


def write_app_paths(path):
    """The symbol geometry for the app's Logo component (src/ui/Logo.tsx); colours come from tokens."""
    ox, oy = -4, 4
    body = (
        '// Generated by brand/tools/build_masters.py from the logo geometry. Do not edit.\n'
        '// src/ui/logo-paths.test.ts checks it against brand/masters/symbol.svg.\n'
        f"export const LOGO_BOOK = '{T(BOOK + ' ' + B, 1, ox, oy)}';\n"
        f"export const LOGO_HALO = '{T(HALO, 1, ox, oy)}';\n"
        f"export const LOGO_TAIL = '{T(TAIL, 1, ox, oy)}';\n"
    )
    Path(path).write_text(body)


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--palette', default='o2', choices=PALETTES)
    ap.add_argument('--out', default=str(Path(__file__).resolve().parents[1] / 'masters'))
    a = ap.parse_args()
    build(PALETTES[a.palette], Path(a.out))
    if a.palette == 'o2':
        write_app_paths(Path(__file__).resolve().parents[2] / 'src/ui/logo-paths.ts')
    print(f'masters ({a.palette}) -> {a.out}')
